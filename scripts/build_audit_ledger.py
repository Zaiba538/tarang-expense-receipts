
"""Build the audit and exposure ledger for Tarang Pharma claims.

Usage (from the project root):
    python scripts/build_audit_ledger.py [--ocr PATH] [--output PATH]

Inputs (read only):
  data/Task 2 Files/claims_train.csv, claims_test.csv, employees.csv
  reports/ocr_extractions_v3.csv   - OCR fields and raw text per image (or --ocr)
  tarang-expense-receipts/images/  - receipt images, hashed with SHA-256 to
                                     find identical files (git-ignored: the
                                     hashes need a local copy of the images)
  predictions.csv                  - current test decisions; only used for
                                     context and the payer-identity question
  audit/photo_review_findings.csv  - manual photo-review fixture (see below)
Output:
  reports/audit_exposure_ledger.csv (or --output), one row per finding.

Evidence:
  * The photo-review fixture records what a reviewer saw when opening a
    receipt photo (AI-assisted review in this project; no reviewer name or
    date is recorded). It cannot be regenerated by code, only re-checked by
    opening the listed images. A fixture row is used only when its claim ID,
    claimed amount and image prefix match the source records; otherwise it
    becomes an unresolved_record row and is not counted.
  * Everything else is computed with the production checks (duplicate
    detection, receipt integrity, hostile text, vehicle plates) from the
    OCR output and image hashes. Signals from OCR text alone are ocr_lead
    rows: open the photo before acting on them.

Categories:
  confirmed_photo   - confirmed from receipt-photo evidence, or an identical
                      image file (evidence_basis says which);
  probable_photo    - the photo shows the bill contradicting itself, but no
                      visible alteration;
  ocr_lead          - computed from OCR text only;
  retained_copy     - the copy of a duplicated bill treated as the valid
                      claim; carries no exposure and is not a problem claim;
  policy_question   - an eligibility condition the data cannot settle;
  unresolved_record - a fixture row that does not match the source records.

Assumptions:
  * Duplicate groups join claims linked by an identical image, an OCR
    same-bill match or a photo-confirmed same bill. The kept copy is, in
    order: the copy named in the fixture; the claim of the employee whose
    vehicle is on a bill whose colleague plate was photo-confirmed; for a
    single-employee group, the earliest submission. When different
    employees claimed the bill and none of these applies, the payer is
    unknown: no claim is singled out, and one group row carries the group's
    value: the copies' claimed total less the largest amount any one copy
    could validly be paid (its photo-confirmed bill amount, else its claim).
    Member findings already covered by that value are kept in the ledger
    but marked "not counted separately".
  * payer_status records why a copy is kept, never who paid: a photo can
    show whose name or vehicle is on a bill, not who paid for it.
  * An OCR gap between claim and bill is not counted when the clerk note
    records a correction ("corrected") or the clerk-entered bill amount
    agrees with the claim; the row stays in the ledger with that status.
  * Historical claims that were rejected or queried carry no counted
    exposure.

Money is counted once per claim, or once per payer-unknown group.
"excess_over_bill" is what a claim asks for above the bill the evidence
supports; "gross_claim_exposure" is the whole claim when it should not be
paid at all (an extra copy of a bill, a colleague's vehicle). Test-claim
amounts are potential; training-claim payments are not recorded in the
data, so no amount is described as paid or recoverable. A finding describes
evidence, not intent: nothing in this ledger is a finding of misconduct.
"""

