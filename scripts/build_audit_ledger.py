def _money(value: Any) -> Decimal | None:
    return normalize_amount(value)


def _fmt(value: Decimal | None) -> str:
    return "" if value is None else f"{value:.2f}"


def load_photo_findings(path: Path) -> list[dict[str, str]]:
    if not path.is_file():
        return []
    with path.open(newline="", encoding="utf-8") as file:
        return [{key: clean(value) for key, value in row.items()} for row in csv.DictReader(file)]


def check_photo_record(
    record: dict[str, str],
    claims: dict[str, dict[str, Any]],
    receipts: dict[str, dict[str, Any]],
) -> str:
    """Return '' when the record matches the source data, else the problem."""
    claim_id = record.get("claim_id", "")
    claim = claims.get(claim_id)
    if claim is None:
        return f"claim {claim_id or '(blank)'} not in source claims"
    recorded = _money(record.get("recorded_amount_claimed"))
    source = _money(claim.get("amount_claimed"))
    if recorded is None or source is None or recorded != source:
        return f"recorded amount {record.get('recorded_amount_claimed')} != source amount {claim.get('amount_claimed')}"
    image = clean(receipts.get(claim_id, {}).get("image_filename"))
    if not image:
        return "claim has no matched receipt image"
    if record.get("image_prefix") and not image.startswith(record["image_prefix"] + "_"):
        return f"recorded image {record['image_prefix']} != matched image {image[:3]}"
    for related in filter(None, record.get("related_claim_ids", "").split(";")):
        if related not in claims:
            return f"related claim {related} not in source claims"
    return ""


class _UnionFind:
    def __init__(self) -> None:
        self.parent: dict[str, str] = {}

    def find(self, item: str) -> str:
        self.parent.setdefault(item, item)
        while self.parent[item] != item:
            self.parent[item] = self.parent[self.parent[item]]
            item = self.parent[item]
        return item

    def union(self, first: str, second: str) -> None:
        self.parent[self.find(first)] = self.find(second)


def build_ledger(
    claims: list[dict[str, Any]],
    receipts: dict[str, dict[str, Any]],
    employees: list[dict[str, Any]],
    photo_records: list[dict[str, str]],
    decisions: dict[str, str] | None = None,
) -> list[dict[str, Any]]:
    """
    Build ledger rows.

    claims    - claim records with a "split" key ("train" or "test").
    receipts  - claim_id -> OCR receipt fields for claims with a matched
                image (image_filename, vendor, receipt_number, receipt_date,
                total_amount, raw_text, vehicle_no, readable, image_sha256).
    decisions - claim_id -> current predicted decision for test claims.
    """
    decisions = decisions or {}
    by_id = {clean(c.get("claim_id")): c for c in claims if clean(c.get("claim_id"))}
    plates = {clean(e.get("emp_id")): clean(e.get("vehicle_no")) for e in employees}
    registry = {normalize_plate(v): k for k, v in plates.items() if v}
    rows: list[dict[str, Any]] = []

    def add(claim_id: str, category: str, finding_type: str, evidence: str,
            basis: str, **extra: Any) -> dict[str, Any]:
        claim = by_id[claim_id]
        receipt = receipts.get(claim_id, {})
        split = clean(claim.get("split"))
        row = {
            "claim_id": claim_id,
            "split": split,
            "emp_id": clean(claim.get("emp_id")),
            "expense_category": clean(claim.get("category")),
            "submitted_on": clean(claim.get("submitted_on")),
            "decision_context": (
                f"current prediction: {decisions.get(claim_id, 'n/a')}"
                if split == "test"
                else f"historical status: {clean(claim.get('status')) or 'n/a'}"
            ),
            "claimed_amount": _money(claim.get("amount_claimed")),
            "receipt_amount_ocr": _money(receipt.get("total_amount")),
            "photo_supported_amount": None,
            "finding_category": category,
            "finding_type": finding_type,
            "evidence_basis": basis,
            "evidence": evidence,
            "conclusion": CONCLUSIONS.get(category, ""),
            "duplicate_group_id": "",
            "related_claim_ids": "",
            "retained_claim_id": "",
            "payer_status": "",
            "exposure_basis": "",
            "excess_over_bill": None,
            "gross_claim_exposure": None,
            "counted_in_totals": False,
            "counted_measure": "",
            "status": "open",
            "payment_status": PAYMENT_STATUS,
        }
        row.update(extra)
        rows.append(row)
        return row

    # 1. Manual photo findings, used only when they match the source records.
    photo_by_claim: dict[str, list[dict[str, str]]] = defaultdict(list)
    for record in photo_records:
        problem = check_photo_record(record, by_id, receipts)
        claim_id = record.get("claim_id", "")
        if problem:
            if claim_id in by_id:
                add(claim_id, UNRESOLVED, record.get("finding_type", ""),
                    record.get("evidence", ""), "manual photo review record",
                    status=f"record mismatch: {problem}")
            else:
                rows.append({
                    **{column: "" for column in LEDGER_COLUMNS},
                    "claim_id": claim_id, "finding_category": UNRESOLVED,
                    "finding_type": record.get("finding_type", ""),
                    "evidence": record.get("evidence", ""),
                    "conclusion": CONCLUSIONS[UNRESOLVED],
                    "status": f"record mismatch: {problem}",
                    "counted_in_totals": False, "payment_status": PAYMENT_STATUS,
                })
            continue
        photo_by_claim[claim_id].append(record)

    families_by_claim: dict[str, set[str]] = defaultdict(set)
    cleared: set[str] = set()
    for claim_id, records in photo_by_claim.items():
        for record in records:
            kind = record["finding_type"]
            if kind == "cleared_lead":
                cleared.add(claim_id)
                continue
            families_by_claim[claim_id].add(FAMILY.get(kind, kind))
            category = CONFIRMED if record["confidence"] == "confirmed" else PROBABLE
            supported = _money(record.get("photo_supported_amount"))
            claimed = _money(by_id[claim_id].get("amount_claimed"))
            row = add(
                claim_id, category, kind, record["evidence"],
                "receipt photo opened in manual review",
                photo_supported_amount=supported,
                related_claim_ids=record.get("related_claim_ids", ""),
                retained_claim_id=record.get("retained_claim_id", ""),
            )
            if kind in ("altered_total", "overclaim") and supported is not None and claimed is not None:
                row["excess_over_bill"] = max(claimed - supported, Decimal("0"))
                row["conclusion"] = CONCLUSIONS.get((kind, category), "")
            elif kind in ("colleague_vehicle", "colleague_bill"):
                row["gross_claim_exposure"] = claimed
                row["conclusion"] = CONCLUSIONS[kind]
            elif kind == "hostile_text":
                row["conclusion"] = CONCLUSIONS["hostile_text"]

    def lead_status(claim_id: str, family: str) -> str:
        if family == "amount" and claim_id in cleared:
            return "cleared by photo review"
        if family in families_by_claim.get(claim_id, set()):
            return "corroborated by photo finding"
        return "open"

    # 2. Computed signals from OCR and image files.
    dup_input = {
        claim_id: {
            key: receipt.get(key)
            for key in ("vendor", "receipt_number", "total_amount", "receipt_date",
                        "image_sha256", "vehicle_no", "raw_text")
        }
        for claim_id, receipt in receipts.items()
    }
    duplicates = detect_duplicates(list(by_id.values()), dup_input, registry)

    for claim_id, claim in by_id.items():
        receipt = receipts.get(claim_id)
        info = duplicates.get(claim_id, {})
        for other_id, kind in info.get("matched", {}).items():
            if kind == "exact_image":
                add(claim_id, CONFIRMED, "duplicate_exact_image",
                    f"Identical image file to {other_id}.", "identical image file hash",
                    related_claim_ids=other_id)
            elif kind == "same_bill":
                add(claim_id, LEAD, "duplicate_same_bill_ocr",
                    f"Same vendor and receipt number as {other_id}, with matching amount or date (OCR).",
                    "OCR text", related_claim_ids=other_id,
                    status=lead_status(claim_id, "duplicate"))
            elif kind == "parking_overlap":
                add(claim_id, LEAD, "parking_time_conflict",
                    f"Parking time conflict with {other_id}: {info.get('evidence', {}).get(other_id, '')} (OCR).",
                    "OCR text", related_claim_ids=other_id,
                    conclusion=CONCLUSIONS["parking_time_conflict"])
            else:
                add(claim_id, LEAD, "duplicate_possible",
                    f"Possible duplicate of {other_id}: {info.get('reason', '')}",
                    "OCR text", related_claim_ids=other_id)

        if not receipt or not truthy(receipt.get("readable")):
            add(claim_id, POLICY, "missing_receipt_evidence",
                "No matched receipt image." if not receipt else "Receipt image has no readable text.",
                "image matching / OCR")
        else:
            text = clean(receipt.get("raw_text"))
            total = _money(receipt.get("total_amount"))
            claimed = _money(claim.get("amount_claimed"))
            if total is None:
                add(claim_id, POLICY, "missing_receipt_evidence",
                    "OCR could not read the bill total.", "OCR text")

            for finding in check_receipt_integrity(text, receipt.get("total_amount"), claim.get("amount_claimed")):
                add(claim_id, LEAD, f"{finding['code']}", finding["message"], "OCR text",
                    status=lead_status(claim_id, "amount"))

            if total is not None and claimed is not None and not amounts_match(claimed, total):
                add(claim_id, LEAD, "claim_differs_from_ocr_total",
                    f"Claimed {claimed:.2f} vs OCR bill total {total:.2f}.", "OCR text",
                    excess_over_bill=max(claimed - total, Decimal("0")),
                    status=_amount_lead_status(claim, claimed, lead_status(claim_id, "amount")))

            if find_hostile_text(text):
                add(claim_id, LEAD, "hostile_text_ocr",
                    "OCR text contains instructions addressed to approvers or automated processing.",
                    "OCR text", status=lead_status(claim_id, "hostile"))

            if clean(claim.get("category")).casefold() == "fuel":
                emp_id = clean(claim.get("emp_id"))
                vehicle = classify_vehicle(receipt.get("vehicle_no"), plates.get(emp_id, ""), registry, emp_id)
                if vehicle["status"] == "other_employee":
                    add(claim_id, LEAD, "colleague_vehicle_ocr", vehicle["message"], "OCR text",
                        status=lead_status(claim_id, "vehicle"))
                elif vehicle["status"] in ("uncertain", "mismatch"):
                    add(claim_id, LEAD, f"vehicle_{vehicle['status']}", vehicle["message"], "OCR text")
                elif vehicle["status"] == "missing":
                    add(claim_id, POLICY, "vehicle_not_readable", vehicle["message"], "OCR text")

        question = POLICY_QUESTIONS.get(clean(claim.get("category")).casefold())
        if question:
            add(claim_id, POLICY, question[0], question[1], "policy v3.2 vs available data")
        if clean(claim.get("split")) == "test" and decisions.get(claim_id) == "approve":
            add(claim_id, POLICY, "policy_payer_identity",
                "Policy: a bill is claimed once, by the person who paid it. The data cannot show who paid.",
                "policy v3.2 vs available data")

    # 3. Duplicate groups: photo-confirmed pairs, identical images and OCR same-bill matches.
    groups = _UnionFind()
    for claim_id, info in duplicates.items():
        for other_id, kind in info.get("matched", {}).items():
            if kind in ("exact_image", "same_bill"):
                groups.union(claim_id, other_id)
    for claim_id, records in photo_by_claim.items():
        for record in records:
            if record["finding_type"] == "duplicate_same_bill":
                for other_id in filter(None, record.get("related_claim_ids", "").split(";")):
                    groups.union(claim_id, other_id)

    members: dict[str, list[str]] = defaultdict(list)
    for claim_id in list(groups.parent):
        members[groups.find(claim_id)].append(claim_id)

    duplicate_types = {"duplicate_same_bill", "duplicate_exact_image", "duplicate_same_bill_ocr"}
    group_rows: list[dict[str, Any]] = []
    for index, group in enumerate(
        sorted((sorted(m) for m in members.values() if len(m) > 1), key=lambda m: m[0]), start=1
    ):
        group_id = f"DG-{index:03d}"
        retained, payer_status = _retained_copy(group, by_id, receipts, photo_by_claim, registry)
        supported = {
            row["claim_id"]: row["photo_supported_amount"]
            for row in rows
            if row["claim_id"] in group
            and row["finding_category"] == CONFIRMED
            and row["finding_type"] in ("altered_total", "overclaim")
            and row["photo_supported_amount"] is not None
        }
        member_rows = [
            row for row in rows
            if row["claim_id"] in group and row["finding_type"] in duplicate_types
        ]
        for row in member_rows:
            row["duplicate_group_id"] = group_id
            row["related_claim_ids"] = ";".join(c for c in group if c != row["claim_id"])
            row["retained_claim_id"] = retained
            row["payer_status"] = payer_status
            if not retained:
                # Payer unknown: no claim is singled out; the group row carries the money.
                row["gross_claim_exposure"] = None
                if row["finding_category"] != LEAD:
                    row["conclusion"] = CONCLUSIONS["duplicate_payer_unknown"].format(group=group_id)
            elif row["claim_id"] == retained:
                row["gross_claim_exposure"] = Decimal("0")
                if row["finding_category"] != LEAD:
                    row["finding_category"] = RETAINED
                    row["conclusion"] = CONCLUSIONS["duplicate_retained"] + f" Basis: {payer_status}."
            else:
                row["gross_claim_exposure"] = row["claimed_amount"]
                if row["finding_category"] != LEAD:
                    row["conclusion"] = CONCLUSIONS["duplicate"] + f" Basis: {payer_status}."
        if not retained and member_rows:
            group_row = _payer_unknown_group_row(group_id, group, member_rows, by_id, supported)
            group_rows.append(group_row)
            if not group_row["exposure_basis"].startswith("not counted"):
                # The group amount already includes any confirmed excess on its
                # copies; counting a member finding as well would count it twice.
                for row in rows:
                    if (
                        row["claim_id"] in group
                        and row["finding_type"] not in duplicate_types
                        and row["finding_category"] in CATEGORY_RANK
                        and row["status"] == "open"
                        and ((row["gross_claim_exposure"] or 0) > 0 or (row["excess_over_bill"] or 0) > 0)
                    ):
                        row["status"] = f"not counted separately: included in payer-unknown group {group_id}"
    rows.extend(group_rows)

    # 4. Count money once per claim (or once per payer-unknown group),
    #    from its strongest open finding.
    for row in rows:
        row["exposure_basis"] = row.get("exposure_basis") or _exposure_basis(row)
    by_claim: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        if (
            row["finding_category"] in CATEGORY_RANK
            and row["status"] == "open"
            and not row["exposure_basis"].startswith("not counted")
            and ((row["gross_claim_exposure"] or 0) > 0 or (row["excess_over_bill"] or 0) > 0)
        ):
            by_claim[row["claim_id"] or f"group:{row['duplicate_group_id']}"].append(row)
    for candidates in by_claim.values():
        best = min(
            candidates,
            key=lambda r: (
                CATEGORY_RANK[r["finding_category"]],
                -max(r["gross_claim_exposure"] or 0, r["excess_over_bill"] or 0),
            ),
        )
        best["counted_in_totals"] = True
        best["counted_measure"] = (
            "gross_claim_exposure"
            if (best["gross_claim_exposure"] or 0) >= (best["excess_over_bill"] or 0)
            else "excess_over_bill"
        )

    for number, row in enumerate(rows, start=1):
        row["finding_id"] = f"F-{number:04d}"
    return rows


def _retained_copy(
    group: list[str],
    by_id: dict[str, dict[str, Any]],
    receipts: dict[str, dict[str, Any]],
    photo_by_claim: dict[str, list[dict[str, str]]],
    registry: dict[str, str],
) -> tuple[str, str]:
    """
    Decide which copy of a duplicated bill is kept, and on what basis.

    Returns (retained claim ID, payer status); the ID is blank when the
    payer cannot be established. In order:
      1. a retained claim named in the manual photo review;
      2. the claim of the employee who owns the vehicle on a bill whose
         colleague plate was confirmed on the photo;
      3. for a group claimed by a single employee, the earliest submission;
      4. otherwise none: different employees and no evidence of who paid.
    """
    emp_of = {claim_id: clean(by_id[claim_id].get("emp_id")) for claim_id in group}
    same_employee = len(set(emp_of.values())) == 1

    named = next(
        (record["retained_claim_id"] for claim_id in group
         for record in photo_by_claim.get(claim_id, [])
         if record.get("retained_claim_id") in group),
        "",
    )
    if named:
        return named, (
            f"{PAYER_SAME_EMPLOYEE}; copy named in the photo review kept"
            if same_employee else PAYER_OWNER_ON_PHOTO
        )

    for claim_id in group:
        if any(r["finding_type"] == "colleague_vehicle" for r in photo_by_claim.get(claim_id, [])):
            owner = registry.get(normalize_plate(receipts.get(claim_id, {}).get("vehicle_no")), "")
            owned = [c for c in group if emp_of[c] == owner]
            if owned:
                return owned[0], PAYER_VEHICLE_OWNER

    if same_employee:
        earliest = min(group, key=lambda c: (clean(by_id[c].get("submitted_on")), c))
        return earliest, f"{PAYER_SAME_EMPLOYEE}; earliest submission kept"

    return "", PAYER_UNKNOWN


def _payer_unknown_group_row(
    group_id: str,
    group: list[str],
    member_rows: list[dict[str, Any]],
    by_id: dict[str, dict[str, Any]],
    supported: dict[str, Decimal] | None = None,
) -> dict[str, Any]:
    """One row carrying a payer-unknown group's exposure without naming a claim.

    Only copies approved historically or unpaid test claims count. At most
    one of them can be valid, and it can be valid for no more than the bill
    supports. Not knowing which copy is valid, the group is valued at the
    least it can be:

        sum of the copies' claimed amounts
        - the largest amount any single copy could validly be paid for

    where a copy's valid amount is the photo-confirmed bill amount when one
    exists (confirmed altered total or over-claim), and otherwise its
    claimed amount. Unverified OCR amounts are not used. The amount already
    includes any confirmed excess on the copies, so member findings are not
    counted again. With fewer than two such copies nothing is counted here.
    """
    supported = supported or {}

    def eligible(claim: dict[str, Any]) -> bool:
        return clean(claim.get("split")) == "test" or clean(claim.get("status")) == "approved"

    counted_copies = [c for c in group if eligible(by_id[c])]
    claimed = {c: _money(by_id[c].get("amount_claimed")) or Decimal("0") for c in counted_copies}
    if len(counted_copies) >= 2:
        valid_at_most = max(min(supported.get(c, claimed[c]), claimed[c]) for c in counted_copies)
        group_amount = sum(claimed.values(), Decimal("0")) - valid_at_most
    else:
        group_amount = Decimal("0")
    splits = sorted({clean(by_id[c].get("split")) for c in counted_copies or group})
    category = min(
        (row["finding_category"] for row in member_rows if row["finding_category"] in CATEGORY_RANK),
        key=CATEGORY_RANK.__getitem__,
        default=LEAD,
    )
    basis = sorted({row["evidence_basis"] for row in member_rows if row["finding_category"] == category})
    claimants = "; ".join(f"{c} ({clean(by_id[c].get('emp_id'))})" for c in group)

    if len(counted_copies) < 2:
        exposure_basis = "not counted: only one copy was approved historically"
    elif splits == ["test"]:
        exposure_basis = "potential: unpaid test claims"
    elif splits == ["train"]:
        exposure_basis = "historically approved; amount paid not recorded"
    else:
        exposure_basis = "mixed: unpaid test claims and historically approved claims"

    row = {column: "" for column in LEDGER_COLUMNS}
    row.update(
        claim_id="",
        split="+".join(splits),
        decision_context="duplicate group of claims",
        claimed_amount=None,
        receipt_amount_ocr=None,
        photo_supported_amount=None,
        finding_category=category,
        finding_type="duplicate_group_payer_unknown",
        evidence_basis="; ".join(basis),
        evidence=f"Same bill claimed as {claimants}. " + (
            f"Valued at the copies' claimed total {sum(claimed.values(), Decimal('0')):.2f} "
            f"less the largest amount one copy could validly be paid ({valid_at_most:.2f})."
            if len(counted_copies) >= 2
            else "Fewer than two copies were approved or are pending, so no extra copy is valued."
        ),
        conclusion=CONCLUSIONS["duplicate_group"],
        duplicate_group_id=group_id,
        related_claim_ids=";".join(group),
        payer_status=PAYER_UNKNOWN,
        excess_over_bill=None,
        gross_claim_exposure=group_amount,
        counted_in_totals=False,
        status="open",
        exposure_basis=exposure_basis,
        payment_status=PAYMENT_STATUS,
    )
    return row


def _amount_lead_status(claim: dict[str, Any], claimed: Decimal, status: str) -> str:
    """Keep an OCR amount gap open only when the source records do not settle it."""
    if status != "open":
        return status
    if re.search(r"(?i)\bcorrected\b", clean(claim.get("clerk_note"))):
        return "clerk note records a correction to the bill amount"
    clerk = _money(claim.get("clerk_bill_amount"))
    if clerk is not None and amounts_match(claimed, clerk):
        return "clerk-entered bill amount agrees with the claim; OCR total unverified"
    return status


def _exposure_basis(row: dict[str, Any]) -> str:
    if row["finding_category"] not in CATEGORY_RANK:
        return "no amount"
    if row["split"] == "test":
        return "potential: unpaid test claim"
    if row["decision_context"] == "historical status: approved":
        return "historically approved; amount paid not recorded"
    return "not counted: claim was not approved historically"


def summarize(rows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Totals of counted rows by split, category and measure."""
    totals: dict[tuple[str, str, str], list[Any]] = defaultdict(lambda: [0, Decimal("0")])
    for row in rows:
        if not row["counted_in_totals"]:
            continue
        measure = row["counted_measure"]
        key = (row["split"], row["finding_category"], measure)
        totals[key][0] += 1
        totals[key][1] += row[measure]
    return [
        {"split": split, "finding_category": category, "measure": measure,
         "items": count, "amount": amount}
        for (split, category, measure), (count, amount) in sorted(totals.items())
    ]


def load_project_inputs(
    root: Path = ROOT, ocr_file: Path | None = None,
) -> tuple[list, dict, list, list, dict]:
    data_dir = root / "data" / "Task 2 Files"
    train = pd.read_csv(data_dir / "claims_train.csv", dtype=str, keep_default_na=False)
    test = pd.read_csv(data_dir / "claims_test.csv", dtype=str, keep_default_na=False)
    claims = (
        train.assign(split="train").to_dict("records")
        + test.assign(split="test").to_dict("records")
    )
    employees = pd.read_csv(data_dir / "employees.csv", dtype=str, keep_default_na=False).to_dict("records")

    ocr_file = ocr_file or root / "reports" / OCR_FILE.name
    ocr = pd.read_csv(ocr_file, dtype=str, keep_default_na=False)
    ocr["filename_key"] = ocr["image_filename"].map(filename_key)
    counts = ocr["filename_key"].value_counts()
    unique = ocr[ocr["filename_key"].ne("") & ocr["filename_key"].map(counts).eq(1)]
    ocr_by_key = unique.set_index("filename_key").to_dict("index")

    receipts: dict[str, dict[str, Any]] = {}
    for claim in claims:
        ocr_row = ocr_by_key.get(filename_key(claim.get("image_file")))
        if ocr_row is not None:
            receipts[clean(claim.get("claim_id"))] = {
                **{key: clean(value) for key, value in ocr_row.items()},
                "image_sha256": image_sha256(ocr_row.get("image_filename")),
            }

    decisions: dict[str, str] = {}
    predictions = root / "predictions.csv"
    if predictions.is_file():
        frame = pd.read_csv(predictions, dtype=str, keep_default_na=False)
        decisions = dict(zip(frame["claim_id"], frame["decision"]))

    photo_records = load_photo_findings(root / "audit" / "photo_review_findings.csv")
    return claims, receipts, employees, photo_records, decisions


def write_ledger(rows: list[dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=LEDGER_COLUMNS, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({
                column: _fmt(value) if isinstance(value, Decimal) else
                ("" if value is None else value)
                for column, value in row.items()
            })


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ocr", type=Path, default=OCR_FILE)
    parser.add_argument("--output", type=Path, default=OUTPUT_FILE)
    args = parser.parse_args()

